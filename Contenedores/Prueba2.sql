/*-----------------------------------------------------------------------------
2.2 CUERPO: implementacion de los miembros publicos y privados.
-----------------------------------------------------------------------------*/
CREATE OR REPLACE PACKAGE BODY nodoexpress_pkg AS

    -- FUNCION PRIVADA: solo puede utilizarse dentro del package.
    -- Comprueba si el estado pertenece al conjunto permitido por RN4.
    FUNCTION fn_estado_valido (
        p_estado IN VARCHAR2
    ) RETURN BOOLEAN
    IS
    BEGIN
        RETURN p_estado IN (
            'PENDIENTE', 'CONFIRMADO', 'EN_PREPARACION',
            'DESPACHADO', 'ENTREGADO', 'CANCELADO'
        );
    END fn_estado_valido;

    -- Implementacion del miembro publico 1.
    FUNCTION fn_cantidad_pedidos (
        p_estado IN pedido.estado%TYPE
    ) RETURN NUMBER
    IS
        v_cantidad NUMBER;
    BEGIN
        -- Utiliza el miembro privado para validar antes de consultar.
        IF NOT fn_estado_valido(UPPER(p_estado)) THEN
            RAISE_APPLICATION_ERROR(-20020, 'Estado de pedido no valido.');
        END IF;

        SELECT COUNT(*)
          INTO v_cantidad
          FROM pedido
         WHERE estado = UPPER(p_estado);

        RETURN v_cantidad;
    END fn_cantidad_pedidos;

    -- Implementacion del miembro publico 2.
    PROCEDURE pr_reporte_estados
    IS
    BEGIN
        DBMS_OUTPUT.PUT_LINE('REPORTE DESDE PACKAGE NODOEXPRESS_PKG');

        FOR r IN (
            SELECT estado, COUNT(*) AS cantidad
              FROM pedido
             GROUP BY estado
             ORDER BY estado
        ) LOOP
            DBMS_OUTPUT.PUT_LINE(r.estado || ': ' || r.cantidad);
        END LOOP;
    END pr_reporte_estados;

END nodoexpress_pkg;
/


