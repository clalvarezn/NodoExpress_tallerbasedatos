/*-----------------------------------------------------------------------------
4.7 Prueba manual del trigger de stock.
Se utiliza un cliente sin pedido pendiente (cliente 3), bodega 1, producto 1.
El INSERT es directo a las tablas; NO se llama al procedimiento.
El trigger debe descontar 1 unidad y crear un movimiento SALIDA.
Al final se revierte la prueba.
-----------------------------------------------------------------------------*/
DECLARE
    v_pedido_id NUMBER;
    v_stock_antes NUMBER;
    v_stock_despues NUMBER;
BEGIN
    SELECT stock_disponible INTO v_stock_antes
      FROM inventario
     WHERE bodega_id = 1 AND producto_id = 1;

    INSERT INTO pedido (
        cliente_id, bodega_id_origen, ciudad_id_entrega,
        direccion_calle, estado
    ) VALUES (
        3, 1, 1, 'Direccion de prueba trigger', 'PENDIENTE'
    )
    RETURNING pedido_id INTO v_pedido_id;

    INSERT INTO detalle_pedido (
        pedido_id, producto_id, cantidad, precio_unitario
    ) VALUES (
        v_pedido_id, 1, 1, 189990
    );

    SELECT stock_disponible INTO v_stock_despues
      FROM inventario
     WHERE bodega_id = 1 AND producto_id = 1;

    DBMS_OUTPUT.PUT_LINE('Stock antes: ' || v_stock_antes);
    DBMS_OUTPUT.PUT_LINE('Stock despues: ' || v_stock_despues);
    DBMS_OUTPUT.PUT_LINE('Debe disminuir en una unidad.');
    ROLLBACK;
END;
/

/*-----------------------------------------------------------------------------
4.8 Prueba manual del trigger de puntos.
Se inserta directamente un movimiento GANADO de 60 puntos al cliente 2.
El trigger debe recalcular su nivel y asignar PLATA (umbral 50).
La prueba se revierte al terminar.
-----------------------------------------------------------------------------*/
DECLARE
    v_nivel_antes VARCHAR2(30);
    v_nivel_despues VARCHAR2(30);
BEGIN
    SELECT nf.nombre
