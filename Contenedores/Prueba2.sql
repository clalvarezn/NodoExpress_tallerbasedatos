/*-----------------------------------------------------------------------------
3.1 TRIGGER DE FILA: TRG_DETALLE_DESCUENTA_STOCK
Evento: BEFORE INSERT por cada fila en DETALLE_PEDIDO.
Reglas: RN1 y RN2. Consulta inventario por bodega + producto; rechaza si no
existe stock suficiente; descuenta unidades y deja movimiento SALIDA.
El trigger funciona tanto si el INSERT viene de un procedimiento como si se
ejecuta manualmente desde el cliente SQL.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE TRIGGER trg_detalle_descuenta_stock
BEFORE INSERT ON detalle_pedido
FOR EACH ROW
DECLARE
    v_bodega_id pedido.bodega_id_origen%TYPE;
    v_stock     inventario.stock_disponible%TYPE;
BEGIN
    -- Identificar la bodega desde la cual se despacha este pedido.
    SELECT bodega_id_origen
      INTO v_bodega_id
      FROM pedido
     WHERE pedido_id = :NEW.pedido_id;

    -- Bloquear la fila de inventario para evitar que dos operaciones
    -- simultaneas descuenten el mismo stock disponible.
    SELECT stock_disponible
      INTO v_stock
      FROM inventario
     WHERE bodega_id = v_bodega_id
       AND producto_id = :NEW.producto_id
       FOR UPDATE;

    -- Rechazar la linea si el stock de ESA bodega no alcanza.
    IF v_stock < :NEW.cantidad THEN
        RAISE_APPLICATION_ERROR(-20030,
            'Stock insuficiente en bodega ' || v_bodega_id ||
            ' para producto ' || :NEW.producto_id);
    END IF;

    -- Descontar inventario. La restriccion CHECK evita valores negativos.
    UPDATE inventario
       SET stock_disponible = stock_disponible - :NEW.cantidad
     WHERE bodega_id = v_bodega_id
       AND producto_id = :NEW.producto_id;

    -- Mantener trazabilidad de la salida (RN5).
    INSERT INTO movimiento_inventario (
        bodega_id, producto_id, tipo, cantidad, motivo
    ) VALUES (
        v_bodega_id, :NEW.producto_id, 'SALIDA',
        :NEW.cantidad, 'Salida automatica por detalle de pedido ' || :NEW.pedido_id
    );

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20031,
            'No existe inventario para el producto en la bodega de origen.');
END;
/

/*-----------------------------------------------------------------------------
3.2 TRIGGER DE FILA: TRG_RECALCULA_NIVEL_CLIENTE
Evento: AFTER INSERT por cada fila en MOVIMIENTO_PUNTOS.
Regla: RN8. Calcula puntos netos (GANADO - CANJEADO) y asigna el nivel con
mayor puntos_minimos que el cliente haya alcanzado.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE TRIGGER trg_recalcula_nivel_cliente
FOR INSERT ON movimiento_puntos
COMPOUND TRIGGER

    -- Arreglo donde guardaremos los clientes afectados.
    TYPE t_cliente_ids IS TABLE OF cliente.cliente_id%TYPE
        INDEX BY PLS_INTEGER;

    g_clientes t_cliente_ids;
    g_contador PLS_INTEGER := 0;

    -- PRIMERA ETAPA: se ejecuta por cada fila insertada.
    AFTER EACH ROW IS
    BEGIN
        -- Guardamos el ID del cliente, sin consultar MOVIMIENTO_PUNTOS.
        g_contador := g_contador + 1;
        g_clientes(g_contador) := :NEW.cliente_id;
    END AFTER EACH ROW;

    -- SEGUNDA ETAPA: se ejecuta cuando termina toda la sentencia INSERT.
    AFTER STATEMENT IS
        v_puntos_netos NUMBER;
        v_nivel_id     nivel_fidelizacion.nivel_id%TYPE;
    BEGIN

        -- Recorremos los clientes afectados por la inserción.
        FOR i IN 1 .. g_contador LOOP

            -- Ahora sí podemos consultar MOVIMIENTO_PUNTOS,
            -- porque la sentencia INSERT ya terminó.
            SELECT NVL(SUM(
                CASE
                    WHEN tipo = 'GANADO' THEN puntos
                    WHEN tipo = 'CANJEADO' THEN -puntos
                    ELSE 0
                END
            ), 0)
            INTO v_puntos_netos
            FROM movimiento_puntos
            WHERE cliente_id = g_clientes(i);

            -- Buscamos el nivel más alto alcanzado por el cliente.
            SELECT nivel_id
            INTO v_nivel_id
            FROM (
                SELECT nivel_id
                FROM nivel_fidelizacion
                WHERE puntos_minimos <= v_puntos_netos
                ORDER BY puntos_minimos DESC
            )
            WHERE ROWNUM = 1;

            -- Actualizamos automáticamente el nivel del cliente.
            UPDATE cliente
            SET nivel_id = v_nivel_id
            WHERE cliente_id = g_clientes(i);

        END LOOP;

    END AFTER STATEMENT;

END trg_recalcula_nivel_cliente;
/
/*-----------------------------------------------------------------------------
3.3 TRIGGER DE FILA ADICIONAL: TRG_VALIDAR_DEVOLUCION
Evento: BEFORE INSERT por cada fila en DEVOLUCION.
Regla: RN7. Solo se permite solicitar devolucion de pedidos ENTREGADO.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE TRIGGER trg_validar_devolucion
BEFORE INSERT ON devolucion
FOR EACH ROW
DECLARE
    v_estado pedido.estado%TYPE;
BEGIN
    SELECT estado
      INTO v_estado
      FROM pedido
     WHERE pedido_id = :NEW.pedido_id;

    IF v_estado <> 'ENTREGADO' THEN
        RAISE_APPLICATION_ERROR(-20032,
            'RN7: solo se puede solicitar devolucion de un pedido ENTREGADO.');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20033, 'No existe el pedido indicado.');
END;
/

/*-----------------------------------------------------------------------------
3.4 TRIGGER DE SENTENCIA: AUDITORIA DE CAMBIOS EN PEDIDO
La tabla de auditoria almacena una fila por sentencia ejecutada, indicando la
operacion y cuantas filas fueron afectadas. El trigger compuesto acumula el
contador en AFTER EACH ROW y registra el resultado en AFTER STATEMENT.
-----------------------------------------------------------------------------*/

CREATE TABLE auditoria_pedido (
    auditoria_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion       VARCHAR2(10) NOT NULL,
    filas_afectadas NUMBER NOT NULL,
    fecha_evento    DATE DEFAULT SYSDATE NOT NULL
);

CREATE OR REPLACE TRIGGER trg_auditoria_pedido
FOR INSERT OR UPDATE OR DELETE ON pedido
COMPOUND TRIGGER

    -- Variable compartida por las secciones de esta sentencia.
    v_filas_afectadas PLS_INTEGER := 0;
    v_operacion       VARCHAR2(10);

    -- Se ejecuta una vez por cada fila afectada.
    AFTER EACH ROW IS
    BEGIN
        v_filas_afectadas := v_filas_afectadas + 1;

        IF INSERTING THEN
            v_operacion := 'INSERT';
        ELSIF UPDATING THEN
            v_operacion := 'UPDATE';
        ELSIF DELETING THEN
            v_operacion := 'DELETE';
        END IF;
    END AFTER EACH ROW;

    -- Se ejecuta una sola vez al terminar la sentencia completa.
    AFTER STATEMENT IS
    BEGIN
        IF v_filas_afectadas > 0 THEN
            INSERT INTO auditoria_pedido (
                operacion, filas_afectadas
            ) VALUES (
                v_operacion, v_filas_afectadas
            );
        END IF;
    END AFTER STATEMENT;

END trg_auditoria_pedido;
/


