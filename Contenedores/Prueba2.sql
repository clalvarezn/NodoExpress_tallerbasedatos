/*-----------------------------------------------------------------------------
1.1 FUNCION CON PARAMETRO: FN_TOTAL_PEDIDO
Objetivo: calcular RN6 = subtotal - descuento de cupon + costo de envio.
El parametro es el identificador del pedido que se desea consultar.
Nota del modelo: TARIFA_ENVIO tiene una fila de tarifa por ciudad en la carga
piloto y no hay peso de producto en PRODUCTO. Se usa el menor costo registrado
para la ciudad de destino; este alcance debe quedar documentado.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE FUNCTION fn_total_pedido (
    p_pedido_id IN pedido.pedido_id%TYPE
) RETURN NUMBER
IS
    v_subtotal       NUMBER(12,2) := 0;
    v_descuento      NUMBER(12,2) := 0;
    v_costo_envio    NUMBER(12,2) := 0;
    v_ciudad_destino pedido.ciudad_id_entrega%TYPE;
BEGIN
    -- 1) Obtener la ciudad de destino del pedido.
    SELECT ciudad_id_entrega
      INTO v_ciudad_destino
      FROM pedido
     WHERE pedido_id = p_pedido_id;

    -- 2) Sumar el valor de todas las lineas del pedido.
    SELECT NVL(SUM(cantidad * precio_unitario), 0)
      INTO v_subtotal
      FROM detalle_pedido
     WHERE pedido_id = p_pedido_id;

    -- 3) Obtener el descuento aplicado. La PK de PEDIDO_CUPON
    --    garantiza como maximo un cupon por pedido.
    SELECT NVL(SUM(monto_descontado), 0)
      INTO v_descuento
      FROM pedido_cupon
     WHERE pedido_id = p_pedido_id;

    -- 4) Buscar la tarifa asociada a la ciudad de destino.
    --    MIN evita duplicar el resultado si en el futuro hay varias
    --    tarifas para una ciudad; el modelo piloto tiene una por ciudad.
    SELECT NVL(MIN(costo), 0)
      INTO v_costo_envio
      FROM tarifa_envio
     WHERE ciudad_id = v_ciudad_destino;

    -- 5) Retornar el total final del pedido.
    RETURN v_subtotal - v_descuento + v_costo_envio;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20001,
            'No existe el pedido indicado: ' || p_pedido_id);
END fn_total_pedido;
/

/*-----------------------------------------------------------------------------
1.2 FUNCION SIN PARAMETROS: FN_CANTIDAD_PEDIDOS_PENDIENTES
Objetivo: entregar un indicador operativo general, contando todos los pedidos
que actualmente se encuentran PENDIENTE. No necesita parametros porque calcula
un dato global de la operacion.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE FUNCTION fn_cantidad_pedidos_pendientes
RETURN NUMBER
IS
    v_total NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO v_total
      FROM pedido
     WHERE estado = 'PENDIENTE';

    RETURN v_total;
END fn_cantidad_pedidos_pendientes;
/

/*-----------------------------------------------------------------------------
1.3 PROCEDIMIENTO CON PARAMETROS: PR_REGISTRAR_PEDIDO
Objetivo: registrar un pedido completo de una sola linea, aplicando RN3 y RN6.
- Comprueba que el cliente no tenga otro pedido PENDIENTE (RN3).
- Crea la cabecera del pedido.
- Inserta el detalle. El trigger de fila descontara stock y registrara
  MOVIMIENTO_INVENTARIO.
- Valida y registra un cupon opcional.
- Calcula el total y registra el pago como PENDIENTE.
- SAVEPOINT/ROLLBACK TO garantizan que si algo falla, no quede una operacion
  incompleta. No ejecuta COMMIT para no confirmar transacciones ajenas.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE PROCEDURE pr_registrar_pedido (
    p_cliente_id       IN pedido.cliente_id%TYPE,
    p_bodega_id        IN pedido.bodega_id_origen%TYPE,
    p_ciudad_entrega   IN pedido.ciudad_id_entrega%TYPE,
    p_direccion        IN pedido.direccion_calle%TYPE,
    p_producto_id      IN detalle_pedido.producto_id%TYPE,
    p_cantidad         IN detalle_pedido.cantidad%TYPE,
    p_medio_pago       IN pago.medio_pago%TYPE,
    p_codigo_cupon     IN cupon.codigo%TYPE DEFAULT NULL,
    p_pedido_id        OUT pedido.pedido_id%TYPE
)
IS
    v_pedidos_pendientes NUMBER;
    v_precio             producto.precio%TYPE;
    v_subtotal           NUMBER(12,2);
    v_descuento          NUMBER(12,2) := 0;
    v_porcentaje         cupon.descuento_pct%TYPE;
    v_monto_minimo       cupon.monto_minimo%TYPE;
    v_cupon_id           cupon.cupon_id%TYPE;
    v_usos_actuales      cupon.usos_actuales%TYPE;
    v_usos_maximos       cupon.usos_maximos%TYPE;
    v_total              NUMBER(12,2);
BEGIN
    -- Marca el punto al que volveremos si ocurre cualquier error.
    SAVEPOINT sp_inicio_registro_pedido;

    -- Validaciones basicas de entrada.
    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'La cantidad debe ser mayor que cero.');
    END IF;

    IF p_medio_pago NOT IN ('WEBPAY','TRANSFERENCIA','EFECTIVO') THEN
        RAISE_APPLICATION_ERROR(-20011, 'Medio de pago no permitido.');
    END IF;

    -- RN3: el cliente no puede mantener dos pedidos PENDIENTE.
    SELECT COUNT(*)
      INTO v_pedidos_pendientes
      FROM pedido
     WHERE cliente_id = p_cliente_id
       AND estado = 'PENDIENTE';

    IF v_pedidos_pendientes > 0 THEN
        RAISE_APPLICATION_ERROR(-20012,
            'RN3: el cliente ya tiene un pedido PENDIENTE.');
    END IF;

    -- Consultar precio y comprobar que el producto exista y este activo.
    SELECT precio
      INTO v_precio
      FROM producto
     WHERE producto_id = p_producto_id
       AND activo = 'S';

    -- Crear cabecera del pedido. Se inicia en PENDIENTE.
    INSERT INTO pedido (
        cliente_id, bodega_id_origen, ciudad_id_entrega,
        direccion_calle, estado
    ) VALUES (
        p_cliente_id, p_bodega_id, p_ciudad_entrega,
        p_direccion, 'PENDIENTE'
    )
    RETURNING pedido_id INTO p_pedido_id;

    -- Insertar detalle. El trigger TRG_DETALLE_DESCUENTA_STOCK se encarga
    -- de validar y descontar el inventario de la bodega de origen.
    INSERT INTO detalle_pedido (
        pedido_id, producto_id, cantidad, precio_unitario
    ) VALUES (
        p_pedido_id, p_producto_id, p_cantidad, v_precio
    );

    -- Calcular subtotal de la linea.
    v_subtotal := p_cantidad * v_precio;

    -- Si se informo un cupon, validar vigencia, estado, usos y monto minimo.
    IF p_codigo_cupon IS NOT NULL THEN
        SELECT cupon_id, descuento_pct, monto_minimo,
               usos_actuales, usos_maximos
          INTO v_cupon_id, v_porcentaje, v_monto_minimo,
               v_usos_actuales, v_usos_maximos
          FROM cupon
         WHERE UPPER(codigo) = UPPER(p_codigo_cupon)
           AND activo = 'S'
           AND TRUNC(SYSDATE) BETWEEN TRUNC(fecha_inicio) AND TRUNC(fecha_fin)
         FOR UPDATE;

        IF v_usos_actuales >= v_usos_maximos THEN
            RAISE_APPLICATION_ERROR(-20013, 'El cupon alcanzo su limite de usos.');
        END IF;

        IF v_subtotal < v_monto_minimo THEN
            RAISE_APPLICATION_ERROR(-20014,
                'El pedido no alcanza el monto minimo del cupon.');
        END IF;

        v_descuento := ROUND(v_subtotal * v_porcentaje / 100, 2);

        INSERT INTO pedido_cupon (pedido_id, cupon_id, monto_descontado)
        VALUES (p_pedido_id, v_cupon_id, v_descuento);

        UPDATE cupon
           SET usos_actuales = usos_actuales + 1
         WHERE cupon_id = v_cupon_id;
    END IF;

    -- Calcular el total usando la funcion RN6.
    v_total := fn_total_pedido(p_pedido_id);

    -- Registrar el pago asociado al pedido. Queda PENDIENTE hasta confirmacion.
    INSERT INTO pago (pedido_id, medio_pago, monto, estado)
    VALUES (p_pedido_id, p_medio_pago, v_total, 'PENDIENTE');

    DBMS_OUTPUT.PUT_LINE('Pedido registrado correctamente. ID: ' || p_pedido_id);
    DBMS_OUTPUT.PUT_LINE('Subtotal: ' || TO_CHAR(v_subtotal));
    DBMS_OUTPUT.PUT_LINE('Descuento: ' || TO_CHAR(v_descuento));
    DBMS_OUTPUT.PUT_LINE('Total con envio: ' || TO_CHAR(v_total));

EXCEPTION
    WHEN OTHERS THEN
        -- Deshace cabecera, detalle, stock, movimiento, cupon y pago
        -- creados desde el SAVEPOINT; luego informa el error original.
        ROLLBACK TO sp_inicio_registro_pedido;
        RAISE;
END pr_registrar_pedido;
/

/*-----------------------------------------------------------------------------
1.4 PROCEDIMIENTO SIN PARAMETROS: PR_REPORTE_PEDIDOS_ESTADO
Objetivo: mostrar un reporte operativo con la cantidad de pedidos por estado.
No recibe parametros porque informa el estado general de todos los pedidos.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE PROCEDURE pr_reporte_pedidos_estado
IS
BEGIN
    DBMS_OUTPUT.PUT_LINE('REPORTE DE PEDIDOS POR ESTADO');
    DBMS_OUTPUT.PUT_LINE('----------------------------');

    FOR r IN (
        SELECT estado, COUNT(*) AS cantidad
          FROM pedido
         GROUP BY estado
         ORDER BY estado
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(r.estado || ': ' || r.cantidad);
    END LOOP;
END pr_reporte_pedidos_estado;
/

